#!/usr/bin/env python3
"""Copy the bundled entry.png to the output directory.

The image is generated by gen_image_20261122.py and stored beside this
program; the program itself only copies bytes, so both runs write the
same file. Standard library only, no network.
"""
import os
import shutil
import sys


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    src = os.path.join(here, "entry.png")
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    os.makedirs(out_dir, exist_ok=True)
    dst = os.path.join(out_dir, "entry.png")
    shutil.copyfile(src, dst)
    # Guard the gate: the copied file must be byte-identical to the source,
    # so the two runs the grader performs write exactly the same bytes.
    if os.path.getsize(dst) != os.path.getsize(src):
        raise SystemExit("entry.png copy size mismatch")
    return 0


if __name__ == "__main__":
    sys.exit(main())
